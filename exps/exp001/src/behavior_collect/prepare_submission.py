"""Write the submission's R1Pro gateway task config from the BEHAVIOR collection configs.

The submission runner reads ``env_configs/gateway/r1pro.yaml`` for every BEHAVIOR
task (``capx.submission.runner.resolve_task_config_path``) and replaces
``{task_instruction}`` with the instruction the gateway sends. To train on what the
model will see, the prompt template and multi-turn prompt here are derived from the
collection configs (``configs/behavior_tasks/*.yaml``), and every task's collection
prompt must be reproduced exactly with its collection instruction (the manifest
instruction, or a collection-only override from ``behavior_collect.prepare.INSTRUCTION_OVERRIDES``). Servers keep the competition defaults;
the shim knobs are the competition defaults plus ``behavior_collect.parity.KNOB_OVERRIDES``
(a slower base servo), exactly what ``behavior_collect/parity.py`` emulates during collection.

Output: ``exps/exp001/submission/gateway/r1pro.yaml``. Copy it into the image's
``env_configs/gateway/`` (e.g. next to the baseline's ``submission/gateway/*.yaml``
before running ``submission/install.sh``).
"""
from __future__ import annotations

if __package__ in (None, ""):
    # Run as a file: put src/ (not this package directory) first on sys.path so
    # sibling modules are imported through the package and cannot shadow others.
    import sys as _sys
    from pathlib import Path as _Path
    _here = _Path(__file__).resolve().parent
    _sys.path[:] = [p for p in _sys.path if _Path(p or ".").resolve() != _here]
    _sys.path.insert(0, str(_here.parent))

from pathlib import Path

import yaml

from behavior_collect.parity import submission_knob_values
from behavior_collect.prepare import CAPX, EXP, ROOT, dump, task_instruction

PLACEHOLDER = "{task_instruction}"
OUTPUT = EXP / "submission/gateway/r1pro.yaml"


def manifest_instructions() -> dict[str, str]:
    pack = yaml.safe_load((CAPX / "taskpacks/original/pack.yaml").read_text())
    return {t["task_id"]: t["instruction"] for t in pack["tasks"] if t["simulator"] == "behavior"}


def build() -> dict:
    instructions = manifest_instructions()
    split = yaml.safe_load((ROOT / "evaluation/split.yaml").read_text())
    tasks = split["development_task_ids"]["behavior"]
    templates, multi_turn, apis = set(), set(), set()
    for task in tasks:
        cfg = yaml.safe_load((EXP / f"configs/behavior_tasks/{task}.yaml").read_text())["env"]["cfg"]
        # Collection prompts carry the manifest instruction, or its collection-only
        # override (behavior_collect.prepare.INSTRUCTION_OVERRIDES); either way the
        # surrounding template is what the submission must reproduce.
        prompt, instruction = cfg["prompt"], task_instruction(task, instructions[task])
        if prompt.count(instruction) != 1 or PLACEHOLDER in prompt:
            raise ValueError(f"{task}: collection prompt does not contain the collection instruction exactly once")
        templates.add(prompt.replace(instruction, PLACEHOLDER))
        multi_turn.add(cfg["multi_turn_prompt"])
        apis.add(tuple(cfg["apis"]))
    if len(templates) != 1 or len(multi_turn) != 1 or len(apis) != 1:
        raise ValueError("Collection configs disagree on the prompt template, multi-turn prompt or APIs")
    default = yaml.safe_load((CAPX / "env_configs/gateway/r1pro.yaml").read_text())
    config = {
        "apis": list(apis.pop()),
        "prompt": templates.pop(),
        "multi_turn_prompt": multi_turn.pop(),
        "api_servers": default["api_servers"],
        "record_video": default.get("record_video", True),
        # Same knobs as collection (behavior_collect.parity.KNOB_OVERRIDES: slower base servo).
        "r1pro": submission_knob_values(),
    }
    from capx.submission.interfaces import TaskRunConfig
    TaskRunConfig(**config)  # the runner's own schema
    return config


def main() -> None:
    config = build()
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "# R1Pro (BEHAVIOR) gateway task config for the submission image.\n"
        "# Generated by exps/exp001/src/behavior_collect/prepare_submission.py from configs/behavior_tasks/*.yaml;\n"
        "# the prompt and multi-turn prompt match the BEHAVIOR training data. Do not edit by hand.\n"
        + dump(config))
    print(f"[submission] wrote {OUTPUT}")


if __name__ == "__main__":
    main()
